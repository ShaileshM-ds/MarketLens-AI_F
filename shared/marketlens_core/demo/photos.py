"""Openly licensed stock photos for Demo products (stored in frontend/public/demo-photos/, credited in
credits.json). Each Demo product uses one of its category's photos, in order; categories without a suitable
photo keep the local SVG artwork. Photos show a similar product, never the fictional product itself.

Run `python -m marketlens_core.demo.photos` to regenerate frontend/src/lib/demoPhotos.ts.
"""

import json
from pathlib import Path

from .artwork import demo_products

ROOT = Path(__file__).resolve().parents[3]
CREDITS = ROOT / "frontend" / "public" / "demo-photos" / "credits.json"
TS = ROOT / "frontend" / "src" / "lib" / "demoPhotos.ts"
# Where to centre a square crop (CSS object-position): keeps the garment in view and people's heads out of it.
FOCUS = {"womens-clothing-1.jpg": "50% 72%", "mens-clothing-4.jpg": "50% 22%"}


def demo_photo_map() -> dict:
    credits = json.loads(CREDITS.read_text(encoding="utf-8"))
    by_cat: dict[str, list] = {}
    for c in credits:
        by_cat.setdefault(c["category"], []).append(c)
    out, seen = {}, {}
    for p in demo_products():
        options = by_cat.get(p["category"])
        if not options:
            continue
        k = seen.get(p["category"], 0)
        seen[p["category"]] = k + 1
        c = options[k % len(options)]
        out[p["product_id"]] = {"src": f"/demo-photos/{c['file']}", "focus": FOCUS.get(c["file"], "50% 50%"), "title": c["title"],
                                "author": c["author"], "license": c["license"], "licenseUrl": (c.get("license_url") or "").replace("http://creativecommons.org", "https://creativecommons.org"), "source": c["source"]}
    return out


def render_ts(m: dict) -> str:
    return ("// Generated by `python -m marketlens_core.demo.photos`. Do not edit by hand.\n"
            "// Openly licensed stock photos of similar products (Wikimedia Commons), stored locally; see public/demo-photos/credits.json.\n"
            "export interface DemoPhoto { src: string; focus: string; title: string; author: string; license: string; licenseUrl: string; source: string }\n"
            f"export const DEMO_PHOTOS: Record<string, DemoPhoto> = {json.dumps(m, indent=2, ensure_ascii=False, sort_keys=True)};\n")


if __name__ == "__main__":
    TS.write_text(render_ts(demo_photo_map()), encoding="utf-8", newline="\n")
    print("wrote", TS)
